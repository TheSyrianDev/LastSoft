#!/usr/bin/env python3
"""Turn Omarchy's shipped themes into the site's theme CSS.

    python3 tools/build-themes.py [--themes-dir DIR]

Writes `themes.css` (one block of custom properties per theme, all values
resolved so the browser needs no colour maths) and `themes.js` (the names,
light/dark flag and a swatch for the picker). The site's own palette is not
generated: it stays in `style.css` under `:root`, and `data-theme="last"`
simply uses it.

The colours come from `colors.toml`, the same file Omarchy's theme switcher
writes, so a theme here and the desktop agree.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

DEFAULT_DIRS = [
    pathlib.Path.home() / ".local/share/omarchy/themes",
    pathlib.Path("/usr/share/omarchy/themes"),
]

# Shipped themes whose folder name does not title-case nicely.
NAMES = {
    "catppuccin-latte": "Catppuccin Latte",
    "flexoki-light": "Flexoki Light",
    "last-horizon": "Last Horizon",
    "matte-black": "Matte Black",
    "osaka-jade": "Osaka Jade",
    "retro-82": "Retro 82",
    "rose-pine": "Rose Pine",
    "tokyo-night": "Tokyo Night",
    "vantablack": "Vantablack",
}


def title(folder: str) -> str:
    if folder in NAMES:
        return NAMES[folder]
    return " ".join(part.capitalize() for part in folder.split("-"))


def read_colours(path: pathlib.Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    out: dict[str, str] = {}
    for line in text.splitlines():
        if line.lstrip().startswith("#"):
            continue
        # the hashes in "#0c0b0c" are values, so only whole-line comments go.
        match = re.match(r"\s*([A-Za-z0-9_]+)\s*=\s*\"([^\"]+)\"", line)
        if match:
            out[match.group(1)] = match.group(2)
    return out


def rgb(hex_colour: str) -> tuple[int, int, int]:
    value = hex_colour.lstrip("#")
    if len(value) == 3:
        value = "".join(c * 2 for c in value)
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def hex_of(colour: tuple[float, float, float]) -> str:
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(c))) for c in colour)


def mix(a: str, b: str, t: float) -> str:
    pa, pb = rgb(a), rgb(b)
    return hex_of(tuple(pa[i] + (pb[i] - pa[i]) * t for i in range(3)))


def alpha(colour: str, a: float) -> str:
    r, g, b = rgb(colour)
    return f"rgba({r}, {g}, {b}, {a:.2f})"


def luminance(colour: str) -> float:
    def channel(c: float) -> float:
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = rgb(colour)
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def on(colour: str) -> str:
    """Text that sits on `colour`: black or white, whichever wins the contrast."""
    light = (luminance(colour) + 0.05) / 0.05
    dark = 1.05 / (luminance(colour) + 0.05)
    return "#000000" if light >= dark else "#ffffff"


def tokens(colours: dict[str, str]) -> dict[str, str]:
    ground = colours["background"]
    ink = colours["foreground"]
    accent = colours.get("accent") or colours.get("blue") or ink
    secondary = colours.get("orange") or colours.get("yellow") or accent
    leaf = colours.get("green") or accent
    muted = mix(ink, ground, 0.34)
    return {
        "--ground": ground,
        "--ground-2": mix(ground, ink, 0.06),
        "--ground-3": mix(ground, ink, 0.10),
        "--ink": ink,
        "--muted": muted,
        "--accent": accent,
        "--accent-2": secondary,
        "--leaf": leaf,
        "--selection": colours.get("selection") or mix(ground, ink, 0.16),
        "--hair": alpha(ink, 0.14),
        "--hair-strong": alpha(ink, 0.28),
        "--tint": alpha(accent, 0.06),
        "--glow": alpha(accent, 0.055),
        "--scroll": mix(ground, ink, 0.18),
        "--scroll-hover": mix(ground, ink, 0.26),
        "--on-accent": on(accent),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--themes-dir", action="append", default=None)
    args = parser.parse_args()

    dirs = [pathlib.Path(d) for d in args.themes_dir] if args.themes_dir else DEFAULT_DIRS
    root = pathlib.Path(__file__).resolve().parent.parent

    found: dict[str, dict[str, str]] = {}
    for base in dirs:
        if not base.is_dir():
            continue
        for theme in sorted(base.iterdir()):
            if theme.name in found:
                continue
            colours = theme / "colors.toml"
            if colours.is_file():
                found[theme.name] = read_colours(colours)
    if not found:
        print("no Omarchy themes found", file=sys.stderr)
        return 1

    css = [
        "/* Generated by tools/build-themes.py from the colors.toml files Omarchy ships.",
        "   Do not edit by hand: re-run the generator instead. The site's own palette",
        "   lives in style.css under :root (data-theme=\"last\"). */",
        "",
    ]
    meta = []
    for folder in sorted(found):
        colours = found[folder]
        mode = colours.get("mode", "dark")
        values = tokens(colours)
        css.append(f'html[data-theme="{folder}"] {{')
        css.append(f"  color-scheme: {mode};")
        for key, value in values.items():
            css.append(f"  {key}: {value};")
        css.append("}")
        css.append("")
        meta.append(
            {
                "id": folder,
                "name": title(folder),
                "mode": mode,
                "swatch": [
                    values["--ground"],
                    values["--ink"],
                    values["--accent"],
                    values["--accent-2"],
                ],
            }
        )

    (root / "themes.css").write_text("\n".join(css), encoding="utf-8")
    (root / "themes.js").write_text(
        "/* Generated by tools/build-themes.py — see themes.css. */\n"
        "window.__LASTAI_THEMES = "
        + json.dumps(meta, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(meta)} themes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
